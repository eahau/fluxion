private fun SvcCompatResult.toGenerated(): GCompatResult {
    val missing = requiredFieldsMissing.map { field ->
        CompatDiagnostic(
            field = field,
            message = "Target required field '$field' is missing from mapped source output"
        )
    }
    val mismatches = typeMismatches.map { tm: TypeMismatch ->
        CompatDiagnostic(
            field = tm.field,
            message = "Type mismatch on '${tm.field}': source types [${tm.sourceTypes.joinToString()}] vs target types [${tm.targetTypes.joinToString()}]",
            expectedType = tm.targetTypes.firstOrNull(),
            actualType = tm.sourceTypes.firstOrNull()
        )
    }
    val warnings = warnings.map { msg ->
        CompatDiagnostic(field = "_", message = msg)
    }
    val dto = GCompatResult(compatible = ok)
    dto.sourceFields = resolvedSourceProjectedTypes.size
    dto.targetRequiredCount = requiredFieldsMissing.size
    dto.missingRequired = missing.toMutableList()
